#' Synthetic IHC reader reproducibility study
#'
#' Three fictional readers score 180 specimens from 90 fictional patients.
#' Numeric scores, ordinal grades and binary calls illustrate clinical-cutoff
#' disagreement, reader-specific accuracy, missing observations, indeterminate
#' calls and repeated specimens. These are generated data, not observations or
#' a reproduction of the Stoieva and Fraga review. The cutoff of 50 is illustrative.
#'
#' @format A data frame with 180 rows and 12 variables:
#' \describe{
#'   \item{case_id}{Unique fictional specimen identifier.}
#'   \item{patient_id}{Fictional patient identifier; two specimens per patient.}
#'   \item{reference}{Reference diagnosis: Absent or Present.}
#'   \item{score1, score2, score3}{Numeric scores between 0 and 100, including missing readings.}
#'   \item{grade1, grade2, grade3}{Ordered grades: Absent, Weak, Moderate, Strong.
#'     Score boundaries are 25, 50 and 75.}
#'   \item{call1, call2, call3}{Negative below 50 and Positive at or above 50,
#'     with additional Indeterminate calls and missing readings.}
#' }
#' @source Generated by \code{data-raw/generate_ihc_reader_reproducibility.R}, seed 20261003.
#' @keywords datasets
